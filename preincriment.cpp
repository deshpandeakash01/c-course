#include <iostream>
using namespace std;

int main() {
    int i = 0;

    cout << "Before pre-increment: " << i << endl; // Outputs 0
    cout << "Using pre-increment (++i): " << ++i << endl; // Increments i to 1, then outputs 1
    cout << "After pre-increment: " << i << endl; // Outputs 1

    return 0;
}




